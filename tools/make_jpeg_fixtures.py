#!/usr/bin/env python3
"""Regenerate the native JPEG decoder's test fixtures.

Each fixture pairs a JPEG written by libjpeg-turbo (through Pillow) with the
pixels libjpeg-turbo decodes it back to. Comparing against an independent
implementation is the only way to know our decoder is correct rather than merely
self-consistent: a round-trip through our own encoder would hide any error the
two sides share.

Usage:
    python3 tools/make_jpeg_fixtures.py
Requires Pillow and NumPy. Writes
engine/native/cpp/tests/fixtures/JpegFixtures.h.
"""

from __future__ import annotations

import os
import pathlib

import numpy as np
from PIL import Image

REPO = pathlib.Path(__file__).resolve().parent.parent
TARGET = REPO / "engine/native/cpp/tests/fixtures/JpegFixtures.h"
SCRATCH = pathlib.Path(os.environ.get("TMPDIR", "/tmp")) / "parallax-jpeg-fixtures"

cases: list[tuple[str, bytes, np.ndarray, tuple[int, int]]] = []


def emit(name: str, image: Image.Image, **save_kwargs) -> None:
    SCRATCH.mkdir(parents=True, exist_ok=True)
    path = SCRATCH / f"{name}.jpg"
    image.save(path, "JPEG", **save_kwargs)
    data = path.read_bytes()
    decoded = np.asarray(Image.open(path).convert("RGB"), dtype=np.uint8)
    cases.append((name, data, decoded, image.size))


def c_array(name: str, data: bytes, per_line: int = 16) -> str:
    lines = []
    for start in range(0, len(data), per_line):
        chunk = data[start : start + per_line]
        lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in chunk) + ",")
    return f"const unsigned char {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def build() -> None:
    rng = np.random.default_rng(7)

    # A smooth gradient with hard edges: exercises DC prediction and AC runs.
    width, height = 64, 48
    gradient = np.zeros((height, width, 3), np.uint8)
    for y in range(height):
        for x in range(width):
            gradient[y, x] = (x * 4 % 256, y * 5 % 256, (x + y) * 3 % 256)
    gradient[10:20, 10:30] = (255, 0, 0)
    gradient[30:40, 40:60] = (0, 255, 0)

    emit("gradient_420", Image.fromarray(gradient), quality=90, subsampling=2)
    emit("gradient_444", Image.fromarray(gradient), quality=95, subsampling=0)
    emit("gradient_422", Image.fromarray(gradient), quality=90, subsampling=1)

    # Dimensions that are not a multiple of the MCU size, so the last MCU of
    # each row and column extends past the image.
    odd = np.zeros((37, 53, 3), np.uint8)
    for y in range(37):
        for x in range(53):
            odd[y, x] = ((x * 7) % 256, (y * 11) % 256, 128)
    emit("odd_size", Image.fromarray(odd), quality=92, subsampling=2)

    grey = (np.add.outer(np.arange(32), np.arange(40)) * 3 % 256).astype(np.uint8)
    emit("grey", Image.fromarray(grey, mode="L"), quality=90)

    # Restart markers reset the DC predictor part-way through the image.
    emit(
        "restarts",
        Image.fromarray(gradient),
        quality=85,
        subsampling=2,
        restart_marker_blocks=2,
    )

    # Noise at low quality: long zero runs and end-of-block symbols.
    noise = rng.integers(0, 256, (40, 40, 3), dtype=np.uint8)
    emit("noise_low_q", Image.fromarray(noise), quality=30, subsampling=2)

    # Flat colour: every AC coefficient zero, hitting the IDCT's DC shortcut.
    emit(
        "flat",
        Image.fromarray(np.full((24, 24, 3), (12, 200, 90), np.uint8)),
        quality=95,
        subsampling=0,
    )


def write_header() -> None:
    parts = [
        "// Generated by tools/make_jpeg_fixtures.py -- do not edit by hand.",
        "//",
        "// Each fixture is a JPEG produced by libjpeg-turbo (through Pillow) together",
        "// with the pixels libjpeg-turbo decodes it to. Testing against an independent",
        "// implementation's output is the only way to know our decoder is right rather",
        "// than merely self-consistent.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace parallax {",
        "namespace jpeg_fixtures {",
        "",
        "struct Fixture {",
        "  const char* name;",
        "  const unsigned char* jpeg;",
        "  size_t jpeg_size;",
        "  const unsigned char* rgb;",
        "  int width;",
        "  int height;",
        "};",
        "",
    ]
    for name, data, decoded, _ in cases:
        key = name.title().replace("_", "")
        parts.append(c_array(f"k{key}Jpeg", data))
        parts.append(c_array(f"k{key}Rgb", decoded.tobytes(), 24))
        parts.append("")

    parts.append("inline const Fixture kFixtures[] = {")
    for name, _, _, size in cases:
        key = name.title().replace("_", "")
        parts.append(
            f'    {{"{name}", k{key}Jpeg, sizeof(k{key}Jpeg), '
            f"k{key}Rgb, {size[0]}, {size[1]}}},"
        )
    parts.append("};")
    parts.append("")
    parts.append(
        "inline constexpr int kFixtureCount = sizeof(kFixtures) / sizeof(kFixtures[0]);"
    )
    parts.append("")
    parts.append("}  // namespace jpeg_fixtures")
    parts.append("}  // namespace parallax")
    TARGET.write_text("\n".join(parts) + "\n")
    print(f"wrote {TARGET} ({TARGET.stat().st_size} bytes, {len(cases)} fixtures)")


if __name__ == "__main__":
    build()
    write_header()
